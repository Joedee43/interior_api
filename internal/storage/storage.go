// Package storage stores opaque files (uploaded images and 3D models) by
// key. Store is the seam for swapping the local disk for object storage
// (S3, R2, ...) later: handlers and services only ever see the interface.
package storage

import (
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var (
	ErrNotFound   = errors.New("stored file not found")
	ErrInvalidKey = errors.New("invalid storage key")
)

// File is an opened stored file. Seeking is required so http.ServeContent
// can answer range requests (partial downloads of large 3D models).
type File interface {
	io.ReadSeekCloser
}

// Store is deliberately small: put, open, delete. Keys are generated by
// the application, never taken from user input.
type Store interface {
	// Put writes r under key and returns the number of bytes written. The
	// file appears atomically: readers see the old state or the complete
	// new file, never a partial one.
	Put(ctx context.Context, key string, r io.Reader) (int64, error)
	Open(ctx context.Context, key string) (File, error)
	// Delete removes key; deleting a missing key is not an error.
	Delete(ctx context.Context, key string) error
}

// keyPattern allows lowercase path segments like "media/3f2a...". No dots,
// so ".." can never appear; no backslashes or drive letters either.
var keyPattern = regexp.MustCompile(`^[a-z0-9-]+(/[a-z0-9-]+){0,3}$`)

// LocalStore keeps files under a root directory on the local disk.
type LocalStore struct {
	root string
}

// NewLocalStore creates root if needed. root is resolved to an absolute
// path so later containment checks are unambiguous.
func NewLocalStore(root string) (*LocalStore, error) {
	abs, err := filepath.Abs(root)
	if err != nil {
		return nil, fmt.Errorf("resolve storage dir: %w", err)
	}
	if err := os.MkdirAll(abs, 0o750); err != nil {
		return nil, fmt.Errorf("create storage dir: %w", err)
	}
	return &LocalStore{root: abs}, nil
}

// path maps a key to a file path, refusing anything that is not a plain
// key or that would resolve outside root. The pattern already rules out
// traversal; the prefix check is defence in depth.
func (s *LocalStore) path(key string) (string, error) {
	if !keyPattern.MatchString(key) {
		return "", ErrInvalidKey
	}
	p := filepath.Join(s.root, filepath.FromSlash(key))
	if !strings.HasPrefix(p, s.root+string(filepath.Separator)) {
		return "", ErrInvalidKey
	}
	return p, nil
}

// Put writes to a temporary file in the destination directory and renames
// it into place. A rename within one directory is atomic, so a crash or a
// failed copy never leaves a half-written file under the real key.
func (s *LocalStore) Put(ctx context.Context, key string, r io.Reader) (n int64, err error) {
	dst, err := s.path(key)
	if err != nil {
		return 0, err
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0o750); err != nil {
		return 0, fmt.Errorf("create directory: %w", err)
	}
	tmp, err := os.CreateTemp(filepath.Dir(dst), ".upload-*")
	if err != nil {
		return 0, fmt.Errorf("create temp file: %w", err)
	}
	// Named result `err` lets this deferred cleanup see whether the
	// function is failing and remove the temp file if so.
	defer func() {
		if err != nil {
			_ = tmp.Close()
			_ = os.Remove(tmp.Name())
		}
	}()

	n, err = io.Copy(tmp, readerWithContext{ctx, r})
	if err != nil {
		return n, fmt.Errorf("write file: %w", err)
	}
	if err = tmp.Sync(); err != nil { // flush to disk before it becomes visible
		return n, fmt.Errorf("sync file: %w", err)
	}
	if err = tmp.Close(); err != nil {
		return n, fmt.Errorf("close file: %w", err)
	}
	if err = os.Rename(tmp.Name(), dst); err != nil {
		return n, fmt.Errorf("rename file: %w", err)
	}
	return n, nil
}

func (s *LocalStore) Open(_ context.Context, key string) (File, error) {
	p, err := s.path(key)
	if err != nil {
		return nil, err
	}
	f, err := os.Open(p)
	if errors.Is(err, os.ErrNotExist) {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("open file: %w", err)
	}
	return f, nil
}

func (s *LocalStore) Delete(_ context.Context, key string) error {
	p, err := s.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(p); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("delete file: %w", err)
	}
	return nil
}

// readerWithContext stops a long copy when the request is cancelled (the
// client disconnects mid-upload), instead of reading until EOF.
type readerWithContext struct {
	ctx context.Context
	r   io.Reader
}

func (r readerWithContext) Read(p []byte) (int, error) {
	if err := r.ctx.Err(); err != nil {
		return 0, err
	}
	return r.r.Read(p)
}
